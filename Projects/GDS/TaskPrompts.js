/**
 * TaskPrompts.js — تعليمات مهام محدّدة
 *
 * يُرفق مع SystemPrompt لكل استدعاء حسب نوع المهمة.
 */

var GDS2 = (typeof GDS2 !== 'undefined') ? GDS2 : {};

GDS2.TaskPrompts = {
  /**
   * مهمة Verifier: مراجعة قرار سابق عن تذكرة — رأي ثانٍ.
   * @param {Object} ctx - { name, passport, previous_result }
   */
  verifier: function(ctx) {
    var prev = ctx.previous_result || {};
    var flag = '';
    if (prev.found === false) {
      flag = 'القرار السابق: الحاج غير موجود في التذكرة. ركّز على مطابقة الاسم بحذر (تحمّل فروق كبيرة في transliteration).';
    } else if (prev.too_many_segments) {
      flag = 'القرار السابق: التذكرة فيها أكثر من قطعتين في اتجاه واحد. **مهم:** Technical stops بنفس رقم الرحلة تُحسب قطعة واحدة. أعد العدّ بحذر.';
    }

    return [
      'مهمتك: مراجعة قرار أول عن تذكرة طيران كـ رأي ثانٍ.',
      '',
      'معلومات الحاج:',
      '- الاسم: ' + (ctx.name || '—'),
      '- الجواز: ' + (ctx.passport || '—'),
      '',
      flag,
      '',
      'التذكرة مرفقة كـ PDF. اقرأها بذكاء مضاعف، وأعد الإجابة بنفس صيغة JSON المعتادة:',
      '{found, matched_name, all_passengers, pnr, airline_detected, airline_code,',
      ' departure_segments_count, return_segments_count, too_many_segments, segments, risks}',
      '',
      '⚠️ مهم:',
      '- إذا اختلفت نتيجتك عن النتيجة السابقة، اكتب حقل "verifier_note" بسطر يشرح السبب.',
      '- إذا Technical stop بنفس رقم الرحلة موجود، ادمج القطعتين في قطعة واحدة.',
      '- إذا وجدت الحاج باسم قريب ولكن مختلف قليلاً، لا تتردد من القبول (transliteration).',
      '',
      'أرجع JSON فقط.'
    ].join('\n');
  },

  /**
   * مهمة Parser: استخراج بيانات الرحلات من نص PDF التذكرة.
   * @param {Object} ctx - { name, passport, pdfText }
   */
  parser: function(ctx) {
    return [
      'مهمتك: استخراج بيانات رحلات تذكرة طيران كـ JSON.',
      '',
      'معلومات الحاج المطلوب:',
      '- الاسم: ' + (ctx.name || '(غير محدد)'),
      '- رقم الجواز: ' + (ctx.passport || '(غير محدد)'),
      '',
      'ابحث في نص التذكرة عن هذا الحاج بالاسم (تحمّل فروق transliteration البسيطة مثل MOHAMED=MOHAMMED=MUHAMMAD).',
      'التذاكر لا تحتوي عادةً على رقم الجواز — اعتمد على الاسم.',
      '',
      '⚠️ **مهم جداً — قراءة PDF متعدد اللغات:**',
      'تذاكر نسك تأتي عادةً بصيغة ثنائية اللغة:',
      '- الصفحات الأولى: نسخة عربية (RTL — قد يخلط ترتيب الكلمات)',
      '- الصفحات التالية: نسخة إنجليزية كاملة (LTR — أوضح للقراءة)',
      'اعتمد على **النسخة الإنجليزية** للاستخراج الدقيق:',
      '- ابحث عن "e-Ticket / Itinerary" أو "Departure from X to Y"',
      '- تجاهل النسخة العربية إن سبّبت ارتباكاً',
      '- اقرأ كل الصفحات حتى النهاية — لا تتوقف عند الصفحة الأولى',
      '- تأكد من **عدّ كل القطع** في كلا الاتجاهين قبل الاستخراج',
      '',
      'الناتج المطلوب — JSON بهذا الهيكل حصراً:',
      '',
      '{',
      '  "found": true أو false,',
      '  "matched_name": "الاسم كما ظهر في التذكرة (عند found=true)",',
      '  "all_passengers": ["قائمة أسماء جميع الركاب في التذكرة"],',
      '  "pnr": "ABC123",',
      '  "airline_detected": "اسم شركة الطيران المُشغّلة",',
      '  "airline_code": "رمز IATA للشركة (مثل SV, MS)",',
      '  "departure_segments_count": عدد قطع الذهاب (1, 2, أو 3),',
      '  "return_segments_count": عدد قطع العودة (1, 2, أو 3),',
      '  "too_many_segments": true إذا وُجد 4+ قطع في اتجاه واحد (نادر جداً),',
      '  "segments": {',
      '    "dep0": null أو كائن قطعة (ترانزيت ذهاب إضافي — الأبعد عن السعودية، فقط عند 3 قطع),',
      '    "dep1": null أو كائن قطعة (ترانزيت الذهاب — قبل الوصول مباشرة, اختياري عند 1-2 قطع),',
      '    "dep2": كائن قطعة (الوصول النهائي — إلزامي),',
      '    "ret1": كائن قطعة (بداية العودة — إلزامي),',
      '    "ret2": null أو كائن قطعة (ترانزيت العودة — بعد الانطلاق مباشرة, اختياري عند 1-2 قطع),',
      '    "ret3": null أو كائن قطعة (ترانزيت عودة إضافي — الأبعد عن السعودية، فقط عند 3 قطع)',
      '  },',
      '  "risks": [',
      '    { "level": "info|warn|critical", "message": "وصف مختصر" }',
      '  ]',
      '}',
      '',
      'شكل كائن القطعة:',
      '{',
      '  "flightNo": "SV127",',
      '  "depDate": "2026-05-10",',
      '  "depTime": "14:30",',
      '  "from": "CAI",',
      '  "to": "JED",',
      '  "arrDate": "2026-05-10",',
      '  "arrTime": "17:45"',
      '}',
      '',
      'قواعد التصنيف:',
      '- dep2 = آخر رحلة تهبط في أي مطار سعودي (JED، MED، RUH، DMM، أو غيرها) — الوصول النهائي، دائماً موجودة',
      '- dep1 = الرحلة قبلها مباشرة (ترانزيت، أي مدينة غير سعودية) — اختياري',
      '- dep0 = الرحلة الأبعد قبل dep1 (ترانزيت إضافي غير سعودي، فقط عند 3 قطع)',
      '- ret1 = أول رحلة تُقلع من أي مطار سعودي (JED، MED، RUH، DMM، أو غيرها) — بداية العودة، دائماً موجودة',
      '- ret2 = الرحلة بعدها مباشرة (ترانزيت عودة، اختياري)',
      '- ret3 = الرحلة الأبعد بعد ret2 (ترانزيت عودة إضافي، فقط عند 3 قطع)',
      '',
      'مثال 3 قطع للذهاب: NYC → DOH → CAI → JED',
      '  dep0 = NYC→DOH, dep1 = DOH→CAI, dep2 = CAI→JED',
      'مثال 3 قطع للعودة: JED → AMS → YVR → NYC',
      '  ret1 = JED→AMS, ret2 = AMS→YVR, ret3 = YVR→NYC',
      '',
      '✅ القاعدة الأساسية: أي مدينة غير سعودية = ترانزيت، بغض النظر عن الدولة',
      '- وصول إلى MED ثم عودة من JED = طبيعي',
      '- وصول إلى RUH أو DMM ثم عودة من JED = طبيعي (الحاج يتنقل براً)',
      '- لا تعتبر هذا "خطأ هيكلي" ولا تضف قطعاً وهمية ولا تترك dep2/ret1 = null بسبب هذا التباين',
      '- القاعدة الصارمة: dep2 = آخر قطعة تهبط في السعودية، ret1 = أول قطعة تُقلع من السعودية',
      '- مثال 2 قطع للذهاب ينتهي بالمدينة + 2 قطع للعودة من جدة:',
      '  ذهاب: JFK → DOH → MED  →  dep1=JFK→DOH, dep2=DOH→MED',
      '  عودة: JED → DOH → JFK  →  ret1=JED→DOH, ret2=DOH→JFK',
      '  (لا تستخدم dep0/ret3 — هما لـ 3 قطع فقط)',
      '',
      '⚠️ ترتيب المعالجة الإلزامي:',
      '1. اقرأ كل أجزاء الرحلة من PDF',
      '2. **ادمج Technical Stops أولاً** (انظر القاعدة أدناه)',
      '3. ثم احسب departure_segments_count و return_segments_count على البيانات **بعد الدمج**',
      '4. الحد الأقصى بعد الدمج: 3 قطع في كل اتجاه',
      '5. فقط لو بعد الدمج يبقى 4+ قطع في اتجاه واحد → too_many_segments=true',
      '',
      '⚠️ قاعدة Technical Stops (إلزامية — تطبَّق قبل العدّ):',
      '- إذا نفس رقم الرحلة (flightNo) يظهر مرتين متتاليتين مع كلمات مثل:',
      '  "Technical stop"، "توقف تقني/فني"، "stop for refuelling"، "تعبئة الوقود"،',
      '  "توقف لأغراض تقنية"، "refuel" بينهما — فهذه **قطعة واحدة** يجب دمجها:',
      '  * flightNo = نفس الرقم',
      '  * from = أول مطار إقلاع (قبل التوقف)',
      '  * to = آخر مطار وصول (بعد التوقف)',
      '  * depDate/depTime = من أول إقلاع',
      '  * arrDate/arrTime = إلى آخر وصول',
      '',
      'أمثلة عملية للدمج:',
      '- QR-1376 DUR→MPM + QR-1376 MPM→DOH (technical stop) = QR-1376 DUR→DOH',
      '- KL-425 RUH→DMM + KL-425 DMM→AMS (technical stop refuel) = KL-425 RUH→AMS',
      '- DMM/MPM/أي توقف تقني = ليس مطار ترانزيت فعلي، تجاهله في العدّ',
      '',
      '✅ الترانزيت الحقيقي: "Waiting time" أو "فترة الانتظار" بين رحلتين **بأرقام مختلفة** → هذه قطعتان فعلاً.',
      '❌ خطأ شائع: عدّ Technical Stop كقطعة منفصلة. هذا يُسبّب too_many_segments خاطئ.',
      '',
      '🔍 تذكير: العدّ يتم **بعد** الدمج، ليس قبله.',
      '',
      'قواعد تحليل المخاطر (risks):',
      '- critical: فشل محقّق (لا PNR، رحلات غير منطقية، بيانات مفقودة)',
      '- warn: تنبيه يستحق المراجعة (layover ضيّق، codeshare، تذكرة حديثة)',
      '- info: ملاحظة غير حرجة',
      '',
      'إذا لم تجد الحاج في التذكرة: أرجع فقط {"found": false, "all_passengers": [...]}',
      '',
      'التذكرة مرفقة كملف PDF في الرسالة. اقرأها مباشرة واستخرج المعلومات المطلوبة.',
      '',
      'أرجع JSON فقط — لا شرح، لا تعليق، لا markdown code block.'
    ].join('\n');
  }
};
